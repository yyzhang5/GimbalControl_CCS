#include "clarke.h"
void clarke_calc(CLARKE *v)
{	
	v->Alpha = v->As;   //令静止坐标系Alpha轴与自然坐标系V(V W U对应A B C)轴电流重合
	v->Beta = v->As*0.5773503 + v->Bs*1.1547005;	// 2/3*sqrt(3)/2=0.5773503=1.1547005/2
}




